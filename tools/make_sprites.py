"""CHix's sprites, drawn as ASCII grids in the HOUSE palette (the pixel-art-gen skill's CHGame defaults).

Writes out/sprites/<name>.json (the skill's input), renders each with the skill's script
(out/sprites/<name>.png, 1x for artkit.craft and <name>_x16.png to look at), a contact sheet, and
CHix/Sprites.h: `static const uint8_t NAME[64]` of HOUSE indices, 255 = transparent.

Run: python tools/make_sprites.py
"""
import json
import os
import subprocess
import sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
OUT = os.path.join(ROOT, 'out', 'sprites')
SKILL = os.path.expanduser('~/.claude/skills/pixel-art-gen/scripts/render_pixel_art.py')

# HOUSE palette: index, hex
HOUSE = {'k': (0, '#000000'), 'w': (1, '#FFFFFF'), 's': (5, '#BBBBCC'), 'r': (6, '#EE1122'), 'm': (7, '#770022'),
         'g': (8, '#FFCC22'), 'b': (10, '#2266EE'), 'n': (11, '#112255'), 'c': (13, '#66EEFF')}


def plate(inner):
    """An 8x8 pick-up icon: an INK-edged plate round a 6x6 picture on navy."""
    rows = ['.kkkkkk.'] + ['k' + r + 'k' for r in inner] + ['.kkkkkk.']
    return rows


SPRITES = {
    'SHIP': ['...kk...',
             '..kwsk..',
             '..kwck..',
             '.kwwssk.',
             'kwwsssbk',
             'kwsbbnbk',
             'kk.rr.kk',
             '...gg...'],
    'SPARK': ['...kk...',
              '..krrk..',
              '.krggrk.',
              'krgwwgrk',
              'krgwwgrk',
              '.krggrk.',
              '..krrk..',
              '...kk...'],
    'PU_FREEZE': plate(['nnccnn', 'nccccn', 'cwwwwc', 'cwwwwc', 'nccccn', 'nnccnn']),
    'PU_SPEED': plate(['nnnggn', 'nnggnn', 'nggggn', 'nnggnn', 'nggnnn', 'ngnnnn']),
    'PU_LASER': plate(['nnrrnn', 'nnrrnn', 'rrwwrr', 'rrwwrr', 'nnrrnn', 'nnrrnn']),
    'PU_SHIELD': plate(['cccccc', 'cwwwwc', 'cwbbwc', 'ncwwcn', 'nnccnn', 'nnnnnn']),
    'PU_SLOW': plate(['nggggn', 'gnnwng', 'gnnwng', 'gnwwng', 'gnnnng', 'nggggn']),
    'PU_BONUS': plate(['nnggnn', 'nnggnn', 'gggggg', 'nggggn', 'nggggn', 'ggnngg']),
    'PU_X2': plate(['gnnnng', 'ngnngn', 'nnggnn', 'nnggnn', 'ngnngn', 'gnnnng']),
    'PU_GHOST': plate(['kwwwwk', 'wwwwww', 'wkwwkw', 'wwwwww', 'wwwwww', 'wkwwkw']),
    'PU_BOMB': plate(['nnnngn', 'nnngnn', 'nmmmmn', 'mmwmmm', 'mmmmmm', 'kmmmmk']),
    'PU_LIFE': plate(['rrnnrr', 'rwrrrr', 'rrrrrr', 'nrrrrn', 'nnrrnn', 'nnnnnn']),
}

os.makedirs(OUT, exist_ok=True)
header = ["// Generated by tools/make_sprites.py: 8x8 sprites as HOUSE-palette indices, 255 = transparent.",
          "#pragma once", "#include <stdint.h>", ""]
sheet = Image.new('RGBA', (len(SPRITES) * 9 * 4, 8 * 4 + 4), (20, 20, 40, 255))
for n, (name, rows) in enumerate(SPRITES.items()):
    assert len(rows) == 8 and all(len(r) == 8 for r in rows), name
    pixels, idx = [], []
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == '.':
                idx.append(255)
            else:
                idx.append(HOUSE[ch][0])
                pixels.append({"x": x, "y": y, "color": HOUSE[ch][1]})
    spec = {"width": 8, "height": 8, "background": "transparent", "grid_lines": False, "pixel_size": 16, "pixels": pixels}
    jp = os.path.join(OUT, name + '.json')
    json.dump(spec, open(jp, 'w'))
    subprocess.run([sys.executable, SKILL, jp, '-o', os.path.join(OUT, name + '_x16.png'), '-p', '16'], check=True,
                   capture_output=True)
    subprocess.run([sys.executable, SKILL, jp, '-o', os.path.join(OUT, name + '.png'), '-p', '1'], check=True,
                   capture_output=True)
    small = Image.open(os.path.join(OUT, name + '.png')).convert('RGBA')
    sheet.alpha_composite(small.resize((32, 32), Image.NEAREST), (n * 36 + 2, 2))
    header.append("static const uint8_t SPR_%s[64] = {" % name.upper())
    for r in range(8):
        header.append("    " + ",".join(str(v) for v in idx[r * 8:r * 8 + 8]) + ",")
    header.append("};")
sheet.save(os.path.join(OUT, 'sheet.png'))
open(os.path.join(ROOT, 'CHix', 'Sprites.h'), 'w', newline='').write("\n".join(header) + "\n")
print("wrote", len(SPRITES), "sprites")
