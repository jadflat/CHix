"""The late-game enemies' wireframes: five more solids for CHix/Shapes.h.

  STAR     a stella octangula: two tetrahedra interlocked (8 corners, 12 edges)
  RING     a drum: two octagons joined at every corner (16 corners, 24 edges)
  CUBOCTA  a cuboctahedron (12 corners, 24 edges)
  SPIRE    a long double pyramid (6 corners, 12 edges)
  CROSS    three bars through a centre, ringed by an octahedron (7 corners, 18 edges)

Corners are in the same units as the earlier shapes (about 16 to 28 from the centre).
Run: python tools/make_shapes.py
"""
import itertools
import math
import os


def carr(name, rows, t):
    return "static const %s %s[%d][%d] = { %s };\n" % (t, name, len(rows), len(rows[0]),
                                                     ", ".join("{%s}" % ",".join(str(v) for v in r) for r in rows))


def edges_by_distance(v, slack=1.05):
    d2 = lambda a, b: sum((x - y) ** 2 for x, y in zip(a, b))
    m = min(d2(v[i], v[j]) for i in range(len(v)) for j in range(i + 1, len(v)))
    return [(i, j) for i in range(len(v)) for j in range(i + 1, len(v)) if d2(v[i], v[j]) <= m * slack]


shapes = {}

# STAR: the two tetrahedra of a cube's corners
a = 17
tetA = [(a, a, a), (a, -a, -a), (-a, a, -a), (-a, -a, a)]
tetB = [(-a, -a, -a), (-a, a, a), (a, -a, a), (a, a, -a)]
verts = tetA + tetB
edges = [(i, j) for i, j in itertools.combinations(range(4), 2)] + [(4 + i, 4 + j) for i, j in itertools.combinations(range(4), 2)]
shapes['STAR'] = (verts, edges)

# RING: two octagons at z = +-6, joined
r = 22
oct_ = [(round(r * math.cos(k * math.pi / 4)), round(r * math.sin(k * math.pi / 4))) for k in range(8)]
verts = [(x, y, -6) for x, y in oct_] + [(x, y, 6) for x, y in oct_]
edges = [(k, (k + 1) % 8) for k in range(8)] + [(8 + k, 8 + (k + 1) % 8) for k in range(8)] + [(k, 8 + k) for k in range(8)]
shapes['RING'] = (verts, edges)

# CUBOCTA
a = 17
verts = []
for s1, s2 in itertools.product((1, -1), repeat=2):
    verts += [(s1 * a, s2 * a, 0), (s1 * a, 0, s2 * a), (0, s1 * a, s2 * a)]
shapes['CUBOCTA'] = (verts, edges_by_distance(verts))
assert len(shapes['CUBOCTA'][1]) == 24

# SPIRE
verts = [(0, -30, 0), (0, 30, 0), (13, 0, 0), (-13, 0, 0), (0, 0, 13), (0, 0, -13)]
edges = [(p, e) for p in (0, 1) for e in (2, 3, 4, 5)] + [(2, 4), (4, 3), (3, 5), (5, 2)]
shapes['SPIRE'] = (verts, edges)

# CROSS: six tips and a centre
t = 24
verts = [(t, 0, 0), (-t, 0, 0), (0, t, 0), (0, -t, 0), (0, 0, t), (0, 0, -t), (0, 0, 0)]
edges = [(6, k) for k in range(6)] + [(i, j) for i in range(6) for j in range(i + 1, 6) if (i // 2) != (j // 2)]
shapes['CROSS'] = (verts, edges)

out = ["// Generated by tools/make_shapes.py: the late-game enemies' wireframes.", "#pragma once", "#include <stdint.h>", ""]
for nm, (v, e) in shapes.items():
    assert len(v) <= 16, nm
    out.append(carr("V_%s" % nm, v, "int8_t").rstrip("\n"))
    out.append(carr("E_%s" % nm, e, "uint8_t").rstrip("\n"))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'CHix', 'Shapes.h'), 'w', newline='').write("\n".join(out) + "\n")
print({k: (len(v), len(e)) for k, (v, e) in shapes.items()})
