"""CHix's music: five techno tracks, played by CHGame's sequencer in LEAD mode (a one-voice piezo: the lead
plays alone, and the bass kick only sounds where the lead rests, so it punches through the gaps).
Writes CHix/Music.h.

A bar is sixteen sixteenth notes. The lead is an acid-style step sequence: each bar picks a 16-step pattern
(offsets from the bar's root note, a rest where the step is None), so every track is a short chord loop over a
four-on-the-floor kick.

Run: python tools/make_music.py
"""
import os
import sys

sys.path.insert(0, os.path.expanduser('~/code/CHGame/tools'))
from music.composer import compile_song  # noqa: E402

NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']


def name(m):
    return "%s%d" % (NAMES[m % 12], m // 12 - 1)


N = None
ACID = [0, 0, N, 12, 0, N, 3, N, 0, 0, 7, N, 10, 0, N, 5]       # the squelchy line
RAVE = [0, N, 7, N, 12, N, 7, N, 0, N, 7, N, 15, N, 12, 7]       # offbeat stabs
DRIVE = [0, 0, 12, 0, 0, 12, 0, 0, 7, 7, 19, 7, 7, 19, 7, 7]     # a pumping octave bounce
STAB = [0, N, N, 0, N, N, 0, N, 12, N, N, 12, N, 7, N, N]        # sparse, for turnarounds


def lead_bar(root, pat):
    return " ".join("R:1" if o is None else "%s:1" % name(root + o) for o in pat)


def kick_bar(root):
    return " ".join("%s:1 R:3" % name(root - 12) for _ in range(4))   # four on the floor


def song(ms, roots, pats):
    assert len(roots) == len(pats) == 8
    lead = " ".join(lead_bar(r, p) for r, p in zip(roots * 2, pats * 2))
    kick = " ".join(kick_bar(r) for r in roots * 2)
    return {"eighth_ms": ms, "voices": [lead, kick]}


SONGS = {
    # title: calm and wide, C minor, 112 bpm
    'TITLE': song(134, [72, 68, 75, 70, 72, 68, 65, 67], [RAVE] * 7 + [STAB]),
    # neon drive: A minor, 128 bpm
    'NEON': song(117, [81, 81, 77, 79, 81, 81, 77, 76], [ACID, ACID, ACID, ACID, DRIVE, DRIVE, ACID, STAB]),
    # chase: E minor, 150 bpm
    'CHASE': song(100, [76, 72, 74, 71, 76, 72, 74, 71], [DRIVE, DRIVE, DRIVE, DRIVE, ACID, ACID, ACID, STAB]),
    # glacier: D minor, 120 bpm
    'GLACIER': song(125, [74, 70, 77, 72, 74, 70, 67, 69], [RAVE, RAVE, RAVE, ACID, RAVE, RAVE, ACID, STAB]),
    # void: C minor, 135 bpm
    'VOID': song(111, [72, 73, 72, 67, 72, 73, 72, 67], [ACID, STAB, ACID, ACID, ACID, STAB, DRIVE, STAB]),
}

out = ["// Generated by tools/make_music.py: five Playtune scores (an acid lead over a kick), played in LEAD mode.",
       "#pragma once", "#include <stdint.h>", ""]
sizes = {}
for nm, sg in SONGS.items():
    data = compile_song(sg, True)
    sizes[nm] = len(data)
    body = ",".join("0x%02X" % b for b in data)
    out.append("static const uint8_t SONG_%s[%d] = {" % (nm, len(data)))
    for i in range(0, len(body), 110):
        out.append("    " + body[i:i + 110])
    out.append("};")
out.append("static const uint8_t *const SONGS[5] = { " + ", ".join("SONG_" + n for n in SONGS) + " };")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'CHix', 'Music.h'), 'w', newline='').write("\n".join(out) + "\n")
print("wrote Music.h:", sizes, sum(sizes.values()), "bytes")
