"""CHix's boss cores: 12x12 pixel art in the HOUSE palette (the pixel-art-gen skill's CHGame defaults).

Each is drawn as its left half (6 columns) and mirrored, so it is symmetric by construction. They are
drawn at the centre of each main enemy's wireframe cage. Renders each with the skill's script
(out/bosses/<name>.png at 1x for artkit.craft, _x16 to look at), writes CHix/Bosses.h
(`BOSS_<NAME>[144]` of HOUSE indices, 255 = transparent) and a contact sheet.

Run: python tools/make_bosses.py
"""
import json
import os
import subprocess
import sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
OUT = os.path.join(ROOT, 'out', 'bosses')
SKILL = os.path.expanduser('~/.claude/skills/pixel-art-gen/scripts/render_pixel_art.py')
HOUSE = {'k': (0, '#000000'), 'w': (1, '#FFFFFF'), 's': (5, '#BBBBCC'), 'r': (6, '#EE1122'), 'm': (7, '#770022'),
         'g': (8, '#FFCC22'), 'b': (10, '#2266EE'), 'n': (11, '#112255'), 'c': (13, '#66EEFF')}

HALVES = {
    'CORE': ['....kk', '..kkcc', '.kccww', '.kcwwg', 'kccwgg', 'kcwwgg', 'kcwwgg', 'kccwgg', '.kcwwg', '.kccww', '..kkcc', '....kk'],
    'CUBE': ['kkkkkk', 'kwwwss', 'kwsssn', 'kssnnn', 'ksnnkk', 'ksnkrr', 'ksnkgr', 'ksnnkk', 'kssnnn', 'knsssn', 'knnnnn', 'kkkkkk'],
    'OCTA': ['.....k', '....kc', '...kcw', '..kcww', '.kcwwc', 'kcwwcb', 'kcwcbb', '.kcbbn', '..kbnn', '...kbn', '....kn', '.....k'],
    'PYRA': ['.....k', '....kg', '...kgg', '...kgg', '..kggr', '..kggr', '.kgggg', '.kgggg', 'kgggmm', 'kggmmm', 'kmmmmm', 'kkkkkk'],
    'PRISM': ['..kkkk', '.kbbww', 'kbbwbb', 'kbbbbb', 'kbnrrr', 'kbbnnn', 'kbbbbb', '.kbbnn', '.knnnn', '..kkkn', '....kk', '.....k'],
    'HEX': ['...kkk', '..kwss', '.kwsss', 'kwsscc', 'ksscww', 'kscwwc', 'kscwwc', 'ksscww', 'kssscc', '.knsss', '..knnn', '...kkk'],
    'ICOSA': ['...kkk', '..kwww', '.kwwww', 'kwwcbb', 'kwcbnn', 'kwcbkk', 'kwcbkk', 'kwwcbn', '.kwwcb', '.kwwwc', '..kmmm', '...kkk'],
    'TESS': ['kkkkkk', 'kggggg', 'kgbbbb', 'kgbkkk', 'kgbkcc', 'kgbkcw', 'kgbkcw', 'kgbkcc', 'kgbkkk', 'kgbbbb', 'kggggg', 'kkkkkk'],
}

os.makedirs(OUT, exist_ok=True)
header = ["// Generated by tools/make_bosses.py: 12x12 boss cores as HOUSE-palette indices, 255 = transparent.",
          "#pragma once", "#include <stdint.h>", ""]
sheet = Image.new('RGBA', (len(HALVES) * 52, 52), (20, 20, 40, 255))
for n, (name, half) in enumerate(HALVES.items()):
    assert len(half) == 12 and all(len(r) == 6 for r in half), name
    rows = [r + r[::-1] for r in half]
    pixels, idx = [], []
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == '.':
                idx.append(255)
            else:
                idx.append(HOUSE[ch][0])
                pixels.append({"x": x, "y": y, "color": HOUSE[ch][1]})
    spec = {"width": 12, "height": 12, "background": "transparent", "grid_lines": False, "pixel_size": 16, "pixels": pixels}
    jp = os.path.join(OUT, name + '.json')
    json.dump(spec, open(jp, 'w'))
    for px, suffix in ((16, '_x16'), (1, '')):
        subprocess.run([sys.executable, SKILL, jp, '-o', os.path.join(OUT, name + suffix + '.png'), '-p', str(px)],
                       check=True, capture_output=True)
    small = Image.open(os.path.join(OUT, name + '.png')).convert('RGBA')
    sheet.alpha_composite(small.resize((48, 48), Image.NEAREST), (n * 52 + 2, 2))
    header.append("static const uint8_t BOSS_%s[144] = {" % name)
    for r in range(12):
        header.append("    " + ",".join(str(v) for v in idx[r * 12:r * 12 + 12]) + ",")
    header.append("};")
header.append("static const uint8_t *const BOSSES[8] = { " + ", ".join("BOSS_" + k for k in HALVES) + " };")
sheet.save(os.path.join(OUT, 'sheet.png'))
open(os.path.join(ROOT, 'CHix', 'Bosses.h'), 'w', newline='').write("\n".join(header) + "\n")
print("wrote", len(HALVES), "bosses")
